"""Generate the poe task appendix from ``poe_tasks/*.toml`` at docs-build time.

The task files' ``help`` strings are the only description of a task that is
maintained with the task itself, so the appendix is built from them rather
than written by hand. Any task without a ``help`` line (other than the
internal ``_``-prefixed helpers) fails the build, which keeps the two in step.
"""
import pathlib
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "developer" / "_poe_tasks.rst"


def collect():
    pyproject = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    includes = pyproject["tool"]["poe"]["include"]
    rows, internal = [], 0
    for rel in includes:
        path = ROOT / rel
        data = tomllib.loads(path.read_text(encoding="utf-8"))
        tasks = data.get("tasks") or data.get("tool", {}).get("poe", {}).get("tasks", {})
        for name, spec in tasks.items():
            if name.startswith("_"):
                internal += 1
                continue
            help_text = spec.get("help", "") if isinstance(spec, dict) else ""
            if not help_text:
                raise RuntimeError(f"poe task {name!r} in {rel} has no help line; add one (docs/_ext/poe_tasks.py)")
            rows.append((name, help_text.strip(), rel))
    rows.sort(key=lambda r: r[0])
    return rows, internal


def cell(text):
    return text.replace("*", r"\*").replace("`", "'").replace("|", r"\|")


def write():
    rows, internal = collect()
    lines = [
        ".. Generated by docs/_ext/poe_tasks.py from poe_tasks/*.toml. Do not edit; edit the task's help line.",
        "",
        ".. list-table::",
        "   :header-rows: 1",
        "   :widths: 26 56 18",
        "",
        "   * - Task",
        "     - What it does",
        "     - Defined in",
    ]
    for name, help_text, rel in rows:
        lines += [f"   * - ``poe {name}``", f"     - {cell(help_text)}", f"     - ``{rel}``"]
    lines += ["", f".. {len(rows)} tasks listed; {internal} internal ``_``-prefixed helpers omitted.", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    return len(rows)


def setup(app):
    write()
    return {"version": "1", "parallel_read_safe": True}
