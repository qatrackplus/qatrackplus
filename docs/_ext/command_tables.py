# Install-guide tables: startup checks and settings defaults


def _render_str(node):
    """Best-effort text of a string expression; placeholders are kept as {…}."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        out = []
        for part in node.values:
            if isinstance(part, ast.Constant):
                out.append(str(part.value))
            elif isinstance(part, ast.FormattedValue):
                out.append('{' + ast.unparse(part.value) + '}')
        return ''.join(out)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Mod):
        return _render_str(node.left)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left, right = _render_str(node.left), _render_str(node.right)
        if left is not None and right is not None:
            return left + right
        return None
    if isinstance(node, ast.Call) and node.args:
        return _render_str(node.args[0])  # _("…"), format(…) and the like
    return None


def startup_checks():
    """One row per Warning/Error constructor in qatrack_core/checks.py that carries a qatrack.* id."""
    path = ROOT / 'qatrack' / 'qatrack_core' / 'checks.py'
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', SyntaxWarning)
        tree = ast.parse(path.read_text(encoding='utf-8'))
    rows = []
    for node in ast.walk(tree):
        if not (
            isinstance(node, ast.Call) and getattr(node.func, 'id', '') in ('Warning', 'Error', 'Info', 'Critical')
        ):
            continue
        kw = {k.arg: k.value for k in node.keywords}
        if 'id' not in kw or not isinstance(kw['id'], ast.Constant):
            continue
        check_id = kw['id'].value
        level = node.func.id
        msg = _render_str(node.args[0]) if node.args else None
        hint = _render_str(kw['hint']) if 'hint' in kw else ''
        rows.append(
            (
                f'``{check_id}``',
                level,
                cell(msg) if msg else '*(message composed at run time; see checks.py)*',
                cell(hint) if hint else '',
            )
        )
    rows.sort()
    out = table(
        ('Id', 'Level', 'What it reports', 'Hint'),
        rows,
        '14 10 44 32',
        'Generated by docs/_ext/command_tables.py from qatrack/qatrack_core/checks.py. Do not edit; edit the check.',
    )
    out += f'\n.. {len(rows)} check constructors.\n'
    (ROOT / 'docs' / 'install' / '_startup_checks.rst').write_text(out, encoding='utf-8')
    return len(rows)


_SECRET_NAME = re.compile(r'SECRET|PASSWORD|PASSWD|_PW$|TOKEN|PRIVATE|API_KEY')


def settings_defaults():
    """Every upper-case module-level assignment in qatrack/settings.py, with its literal default or a note."""
    path = ROOT / 'qatrack' / 'settings.py'
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', SyntaxWarning)
        tree = ast.parse(path.read_text(encoding='utf-8'))
    rows = {}
    for node in tree.body:
        if not (isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name)):
            continue
        name = node.targets[0].id
        if not name.isupper() or name.startswith('_'):
            continue
        if _SECRET_NAME.search(name):
            value = '*(not shown; set it in local_settings.py)*'
        else:
            try:
                literal = ast.literal_eval(node.value)
                text = repr(literal)
                value = '``' + (text if len(text) <= 70 else text[:67] + '...') + '``'
            except (ValueError, TypeError, SyntaxError):
                value = '*(computed at start-up; see settings.py)*'
        rows[name] = value  # a later assignment of the same name wins, as it does in Python
    body = [(f'``{n}``', v) for n, v in sorted(rows.items())]
    out = table(
        ('Setting', 'Default in ``settings.py``'),
        body,
        '36 64',
        'Generated by docs/_ext/command_tables.py from qatrack/settings.py. Do not edit; edit the setting.',
    )
    out += f'\n.. {len(body)} settings.\n'
    (ROOT / 'docs' / 'install' / '_settings_defaults.rst').write_text(out, encoding='utf-8')
    return len(body)


def setup(app):
    poe_tasks()
    manage_commands()
    make_targets()
    startup_checks()
    settings_defaults()
    return {'version': '3', 'parallel_read_safe': True}
