"""Generate the command-reference appendix tables at docs-build time.

Three tables, each read from the thing it describes rather than written by
hand, so none of them can drift from the code:

* poe tasks, from the ``help`` line of each task in the files named under
  ``[tool.poe] include`` in ``pyproject.toml``;
* ``manage.py`` commands that QATrack+ adds, from the ``help`` attribute of
  each ``Command`` class under ``qatrack/*/management/commands/``;
* Makefile targets, described by the target's own ``make help`` line, falling
  back to the ``help`` line of its ``make-*`` poe mirror and then to the comment
  directly above the target.

The fragments land in ``docs/developer/_*.rst`` (gitignored) and are pulled in
by ``docs/developer/commands.rst``. A poe task without a ``help`` line, a
management command without a ``help`` attribute, or a Makefile target with no
description from any of those three places fails the build.

``make help`` is asked first because it is the Makefile's own account of its
own target, and it is the only source that can say a target is **retired**. The
mirror describes the poe task, which for a retired target is a different thing:
asking the mirror first published "the working form of the retired ``make
schema``" as the description of ``make schema`` itself, which reads as though
that target still works.

This order was reversed until 2026-11-05. The Makefile was frozen and could not
be edited, so two stale ``help`` lines could not be fixed there - ``test``
claimed to include the GUI tests ``conftest.py`` now skips by default, and
``test_simple`` claimed to be the one without them. Since make support is being
retired, a broken target is now edited to say so (Cody, 2026-11-05), both stale
lines are corrected, and the Makefile is the better source again. The mirror
stays as the fallback for the five engine targets ``make help`` has never
listed.

The Makefile table also fails the build when a target has no ``make-*`` poe
mirror at all. The Makefile is frozen and goes in the 4.1 cycle; until then
both runners work, and that is only true if the mirror is complete, so the
documentation build is what holds it complete. A dotted target maps to a
dashed task name, because poe rejects a dot in one.
"""

import ast
import pathlib
import re
import tomllib
import warnings

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / 'docs' / 'developer'


def cell(text):
    text = ' '.join(text.split())
    return text.replace('*', r'\*').replace('`', "'").replace('|', r'\|')


def table(header, rows, widths, comment):
    lines = [f'.. {comment}', '', '.. list-table::', '   :header-rows: 1', f'   :widths: {widths}', '']
    lines += [f'   * - {header[0]}'] + [f'     - {h}' for h in header[1:]]
    for row in rows:
        lines += [f'   * - {row[0]}'] + [f'     - {c}' for c in row[1:]]
    return '\n'.join(lines) + '\n'


def load_poe_tasks():
    """``{task name: (spec, the file it came from)}``, in include order."""
    pyproject = tomllib.loads((ROOT / 'pyproject.toml').read_text(encoding='utf-8'))
    tasks = {}
    for rel in pyproject['tool']['poe']['include']:
        data = tomllib.loads((ROOT / rel).read_text(encoding='utf-8'))
        for name, spec in (data.get('tasks') or data.get('tool', {}).get('poe', {}).get('tasks', {})).items():
            tasks[name] = (spec, rel)
    return tasks


def mirror_name(target):
    """The ``make-*`` task that mirrors a Makefile target.

    The dot goes: poe validates task names against ``^[^\W\d][\w:+-]*$``
    (``poethepoet/task/base.py``), so ``make-nginx.conf`` is refused outright.
    ``nginx.conf`` and ``supervisor.conf`` are the only two targets this
    touches.
    """
    return 'make-' + target.replace('.', '-')


def poe_tasks():
    rows, internal = [], 0
    for name, (spec, rel) in load_poe_tasks().items():
        if name.startswith('_'):
            internal += 1
            continue
        help_text = spec.get('help', '') if isinstance(spec, dict) else ''
        if not help_text:
            raise RuntimeError(
                f'poe task {name!r} in {rel} has no help line; add one (docs/_ext/command_tables.py)'
            )
        rows.append((f'``poe {name}``', cell(help_text), f'``{rel}``'))
    rows.sort()
    out = table(
        ('Task', 'What it does', 'Defined in'),
        rows,
        '26 56 18',
        "Generated by docs/_ext/command_tables.py from poe_tasks/*.toml. Do not edit; edit the task's help line.",
    )
    out += f'\n.. {len(rows)} tasks; {internal} internal ``_``-prefixed helpers omitted.\n'
    (OUT_DIR / '_poe_tasks.rst').write_text(out, encoding='utf-8')
    return len(rows)


def _help_attr(path):
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', SyntaxWarning)
        tree = ast.parse(path.read_text(encoding='utf-8'))
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == 'Command':
            for stmt in node.body:
                if isinstance(stmt, ast.Assign) and any(getattr(t, 'id', '') == 'help' for t in stmt.targets):
                    value = stmt.value
                    if isinstance(value, ast.Constant) and isinstance(value.value, str):
                        return value.value
                    if isinstance(value, ast.Call) and value.args and isinstance(value.args[0], ast.Constant):
                        return str(value.args[0].value)
                    return None
    return None


def manage_commands():
    rows, missing = [], 0  # missing stays 0: a gap now raises
    for path in sorted((ROOT / 'qatrack').glob('*/management/commands/*.py')):
        if path.name.startswith('_'):
            continue
        app = path.parents[2].name
        help_text = _help_attr(path)
        if not help_text:
            raise RuntimeError(
                f'management command {path.stem!r} ({path.relative_to(ROOT)}) has no help attribute; '
                'add one (docs/_ext/command_tables.py)'
            )
        help_text = cell(help_text)
        rows.append((f'``manage.py {path.stem}``', help_text, f'``{app}``'))
    out = table(
        ('Command', 'What it does', 'App'),
        rows,
        '30 54 16',
        "Generated by docs/_ext/command_tables.py from qatrack/*/management/commands/. Do not edit; edit the command's help attribute.",
    )
    out += f'\n.. {len(rows)} commands; {missing} without a help attribute.\n'
    (OUT_DIR / '_manage_commands.rst').write_text(out, encoding='utf-8')
    return len(rows), missing


def make_targets():
    text = (ROOT / 'Makefile').read_text(encoding='utf-8')
    lines = text.splitlines()
    tasks = load_poe_tasks()
    # `make help` is the one target with no mirror on purpose: it prints a
    # hand-written list of Makefile targets, and `poe` with no arguments
    # already lists every task. A third copy of that list would be a third
    # thing to fall out of date.
    no_mirror_needed = ('help',)
    missing_mirror = []
    # descriptions from the `help:` recipe: lines like   @echo "  target   description"
    from_help = {}
    for m in re.finditer(r'@echo "  ([A-Za-z0-9_.-]+)\s{2,}(.+?)"', text):
        from_help[m.group(1)] = m.group(2)
    rows, undocumented = [], 0  # undocumented stays 0: a gap now raises
    for i, line in enumerate(lines):
        m = re.match(r'^([A-Za-z0-9_.-]+):(?:\s|$)(?!=)', line)
        if not m or m.group(1) in ('.PHONY', 'help') or m.group(1).startswith('_'):
            continue
        name = m.group(1)
        mirror = tasks.get(mirror_name(name))
        if not mirror and name not in no_mirror_needed:
            missing_mirror.append(name)
        # The Makefile's own `help` line first: it is that file's description of
        # that file's target, and it is the only source that can say a target is
        # retired. The mirror describes the poe task, which for a retired target
        # is a different thing entirely - taking the mirror's help first made the
        # published table say "the working form of the retired `make schema`"
        # against `make schema` itself, which reads as though it still works.
        #
        # This order was the other way round until 2026-11-05, because two
        # `help` lines were stale and the frozen Makefile could not be edited to
        # fix them. Both are now correct, and a broken target is edited to say
        # so, so the Makefile is the better source again. The mirror remains the
        # fallback for the five engine targets `help` has never listed.
        desc = from_help.get(name)
        if not desc and mirror and isinstance(mirror[0], dict):
            desc = mirror[0].get('help')
        if not desc:
            # the comment block directly above the target: take its first line
            j = i - 1
            block = []
            while j >= 0 and lines[j].startswith('#'):
                block.insert(0, lines[j].lstrip('# ').rstrip())
                j -= 1
            desc = block[0] if block else None
        if not desc:
            raise RuntimeError(
                f'Makefile target {name!r} has no help line on {mirror_name(name)!r}, no `make help` '
                'entry and no comment above it; add one (docs/_ext/command_tables.py)'
            )
        desc = cell(desc)
        rows.append((f'``make {name}``', desc))
    if missing_mirror:
        raise RuntimeError(
            'these Makefile targets have no poe mirror: '
            + ', '.join(f'{n} (expected {mirror_name(n)})' for n in sorted(missing_mirror))
            + '. Both runners are meant to work until the Makefile goes in the 4.1 cycle; '
            'add the mirror to poe_tasks/make_compat.toml (docs/_ext/command_tables.py)'
        )
    rows.sort()
    out = table(
        ('Target', 'What it does'),
        rows,
        '30 70',
        'Generated by docs/_ext/command_tables.py from the Makefile. Do not edit; edit `make help` or the comment above the target.',
    )
    out += f'\n.. {len(rows)} targets; {undocumented} without a description.\n'
    (OUT_DIR / '_make_targets.rst').write_text(out, encoding='utf-8')
    return len(rows), undocumented


