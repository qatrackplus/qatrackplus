"""Generate the command-reference appendix tables at docs-build time.

Three tables, each read from the thing it describes rather than written by
hand, so none of them can drift from the code:

* poe tasks, from the ``help`` line of each task in the files named under
  ``[tool.poe] include`` in ``pyproject.toml``;
* ``manage.py`` commands that QATrack+ adds, from the ``help`` attribute of
  each ``Command`` class under ``qatrack/*/management/commands/``;
* Makefile targets, described by the ``make help`` text where the Makefile
  gives one, otherwise by the comment directly above the target.

The fragments land in ``docs/developer/_*.rst`` (gitignored) and are pulled in
by ``docs/developer/commands.rst``. A poe task without a ``help`` line, a
management command without a ``help`` attribute, or a Makefile target with
neither a ``make help`` entry nor a comment above it fails the build.
"""

import ast
import pathlib
import re
import tomllib
import warnings

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / 'docs' / 'developer'


def cell(text):
    text = ' '.join(text.split())
    return text.replace('*', r'\*').replace('`', "'").replace('|', r'\|')


def table(header, rows, widths, comment):
    lines = [f'.. {comment}', '', '.. list-table::', '   :header-rows: 1', f'   :widths: {widths}', '']
    lines += [f'   * - {header[0]}'] + [f'     - {h}' for h in header[1:]]
    for row in rows:
        lines += [f'   * - {row[0]}'] + [f'     - {c}' for c in row[1:]]
    return '\n'.join(lines) + '\n'


def poe_tasks():
    pyproject = tomllib.loads((ROOT / 'pyproject.toml').read_text(encoding='utf-8'))
    rows, internal = [], 0
    for rel in pyproject['tool']['poe']['include']:
        data = tomllib.loads((ROOT / rel).read_text(encoding='utf-8'))
        tasks = data.get('tasks') or data.get('tool', {}).get('poe', {}).get('tasks', {})
        for name, spec in tasks.items():
            if name.startswith('_'):
                internal += 1
                continue
            help_text = spec.get('help', '') if isinstance(spec, dict) else ''
            if not help_text:
                raise RuntimeError(
                    f'poe task {name!r} in {rel} has no help line; add one (docs/_ext/command_tables.py)'
                )
            rows.append((f'``poe {name}``', cell(help_text), f'``{rel}``'))
    rows.sort()
    out = table(
        ('Task', 'What it does', 'Defined in'),
        rows,
        '26 56 18',
        "Generated by docs/_ext/command_tables.py from poe_tasks/*.toml. Do not edit; edit the task's help line.",
    )
    out += f'\n.. {len(rows)} tasks; {internal} internal ``_``-prefixed helpers omitted.\n'
    (OUT_DIR / '_poe_tasks.rst').write_text(out, encoding='utf-8')
    return len(rows)


def _help_attr(path):
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', SyntaxWarning)
        tree = ast.parse(path.read_text(encoding='utf-8'))
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == 'Command':
            for stmt in node.body:
                if isinstance(stmt, ast.Assign) and any(getattr(t, 'id', '') == 'help' for t in stmt.targets):
                    value = stmt.value
                    if isinstance(value, ast.Constant) and isinstance(value.value, str):
                        return value.value
                    if isinstance(value, ast.Call) and value.args and isinstance(value.args[0], ast.Constant):
                        return str(value.args[0].value)
                    return None
    return None


def manage_commands():
    rows, missing = [], 0  # missing stays 0: a gap now raises
    for path in sorted((ROOT / 'qatrack').glob('*/management/commands/*.py')):
        if path.name.startswith('_'):
            continue
        app = path.parents[2].name
        help_text = _help_attr(path)
        if not help_text:
            raise RuntimeError(
                f'management command {path.stem!r} ({path.relative_to(ROOT)}) has no help attribute; '
                'add one (docs/_ext/command_tables.py)'
            )
        help_text = cell(help_text)
        rows.append((f'``manage.py {path.stem}``', help_text, f'``{app}``'))
    out = table(
        ('Command', 'What it does', 'App'),
        rows,
        '30 54 16',
        "Generated by docs/_ext/command_tables.py from qatrack/*/management/commands/. Do not edit; edit the command's help attribute.",
    )
    out += f'\n.. {len(rows)} commands; {missing} without a help attribute.\n'
    (OUT_DIR / '_manage_commands.rst').write_text(out, encoding='utf-8')
    return len(rows), missing


def make_targets():
    text = (ROOT / 'Makefile').read_text(encoding='utf-8')
    lines = text.splitlines()
    # descriptions from the `help:` recipe: lines like   @echo "  target   description"
    from_help = {}
    for m in re.finditer(r'@echo "  ([A-Za-z0-9_.-]+)\s{2,}(.+?)"', text):
        from_help[m.group(1)] = m.group(2)
    rows, undocumented = [], 0  # undocumented stays 0: a gap now raises
    for i, line in enumerate(lines):
        m = re.match(r'^([A-Za-z0-9_.-]+):(?:\s|$)(?!=)', line)
        if not m or m.group(1) in ('.PHONY', 'help') or m.group(1).startswith('_'):
            continue
        name = m.group(1)
        desc = from_help.get(name)
        if not desc:
            # the comment block directly above the target: take its first line
            j = i - 1
            block = []
            while j >= 0 and lines[j].startswith('#'):
                block.insert(0, lines[j].lstrip('# ').rstrip())
                j -= 1
            desc = block[0] if block else None
        if not desc:
            raise RuntimeError(
                f'Makefile target {name!r} has no `make help` entry and no comment above it; '
                'add one (docs/_ext/command_tables.py)'
            )
        desc = cell(desc)
        rows.append((f'``make {name}``', desc))
    rows.sort()
    out = table(
        ('Target', 'What it does'),
        rows,
        '30 70',
        'Generated by docs/_ext/command_tables.py from the Makefile. Do not edit; edit `make help` or the comment above the target.',
    )
    out += f'\n.. {len(rows)} targets; {undocumented} without a description.\n'
    (OUT_DIR / '_make_targets.rst').write_text(out, encoding='utf-8')
    return len(rows), undocumented


def setup(app):
    poe_tasks()
    manage_commands()
    make_targets()
    return {'version': '2', 'parallel_read_safe': True}
